func TestListDevices(t *testing.T) {
	e := newTestServer(t)
	mustDo(t, e, "PUT", locationURL(e, "d2"), map[string]any{"latitude": 2, "longitude": 3, "accuracy": 5})
	mustDo(t, e, "PUT", nicknameURL(e, "d1"), map[string]any{"nickname": "Meu celular"})
	mustDo(t, e, "PUT", locationURL(e, "d1"), map[string]any{"latitude": 1, "longitude": 2})

	resp, data := doRequest(t, e, "GET", e.ts.URL+"/devices", nil)
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("expected 200, got %d", resp.StatusCode)
	}
	if strings.Contains(string(data), `"latitude"`) || strings.Contains(string(data), `"longitude"`) {
		t.Fatalf("device list must not include coordinates: %s", data)
	}
	var out struct {
		Devices []struct {
			DeviceID           string   `json:"deviceId"`
			Nickname           string   `json:"nickname"`
			HasLocation        bool     `json:"hasLocation"`
			PublishedAtEpochMs *int64   `json:"publishedAtEpochMs"`
			Accuracy           *float64 `json:"accuracy"`
		} `json:"devices"`
	}
	if err := json.Unmarshal(data, &out); err != nil {
		t.Fatal(err)
	}
	if len(out.Devices) != 2 {
		t.Fatalf("expected 2 devices, got %d", len(out.Devices))
	}
	if out.Devices[0].DeviceID != "d1" || out.Devices[1].DeviceID != "d2" {
		t.Fatalf("expected sorted devices, got %+v", out.Devices)
	}
	if out.Devices[0].Nickname != "Meu celular" || out.Devices[0].HasLocation != true {
		t.Fatalf("unexpected d1 summary: %+v", out.Devices[0])
	}
	if out.Devices[1].HasLocation != true || out.Devices[1].PublishedAtEpochMs == nil {
		t.Fatalf("unexpected d2 summary: %+v", out.Devices[1])
	}
	if out.Devices[1].Accuracy == nil || *out.Devices[1].Accuracy != 5 {
		t.Fatalf("expected accuracy in list: %+v", out.Devices[1].Accuracy)
	}
}

