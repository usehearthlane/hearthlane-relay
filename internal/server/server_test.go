type env struct {
	ts   *httptest.Server
	path string
	logs *bytes.Buffer
}

func newTestServer(t *testing.T) *env {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "state.json")
	return newTestServerAt(t, path, state.New())
}

func newTestServerAt(t *testing.T, path string, st *state.State) *env {
	t.Helper()
	sts := store.New(path)
	logs := &bytes.Buffer{}
	logger := log.New(logs, "relay: ", 0)
	srv := server.New(st, sts, logger)
	ts := httptest.NewServer(srv.Handler())
	t.Cleanup(ts.Close)
	return &env{ts: ts, path: path, logs: logs}
}

func doRequest(t *testing.T, e *env, method, url string, body any) (*http.Response, []byte) {
	t.Helper()
	var rd io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			t.Fatal(err)
		}
		rd = bytes.NewReader(b)
	}
	req, err := http.NewRequest(method, url, rd)
	if err != nil {
		t.Fatal(err)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatal(err)
	}
	return resp, data
}

func mustDo(t *testing.T, e *env, method, url string, body any) (*http.Response, []byte) {
	t.Helper()
	resp, data := doRequest(t, e, method, url, body)
	if data != nil && (resp.StatusCode < 200 || resp.StatusCode >= 300) {
		t.Fatalf("%s %s: unexpected status %d: %s", method, url, resp.StatusCode, data)
	}
	return resp, data
}

func locationURL(e *env, deviceID string) string {
	return e.ts.URL + "/devices/" + deviceID + "/location"
}

func nicknameURL(e *env, deviceID string) string {
	return e.ts.URL + "/devices/" + deviceID + "/nickname"
}

func TestPublishLocationAndGet(t *testing.T) {
	e := newTestServer(t)
	body := map[string]any{
		"latitude":          -23.55,
		"longitude":         -46.63,
		"accuracy":          50,
		"provider":          "network",
		"recordedAtEpochMs": 1234567890000,
	}
	mustDo(t, e, "PUT", locationURL(e, "hearthlane-ab12cd34"), body)

	resp, data := mustDo(t, e, "GET", locationURL(e, "hearthlane-ab12cd34"), nil)
	if ct := resp.Header.Get("Content-Type"); !strings.Contains(ct, "application/json") {
		t.Fatalf("unexpected content type %q", ct)
	}
	var got struct {
		DeviceID           string   `json:"deviceId"`
		Latitude           float64  `json:"latitude"`
		Longitude          float64  `json:"longitude"`
		Accuracy           *float64 `json:"accuracy"`
		Provider           *string  `json:"provider"`
		RecordedAtEpochMs  *int64   `json:"recordedAtEpochMs"`
		PublishedAtEpochMs int64    `json:"publishedAtEpochMs"`
	}
	if err := json.Unmarshal(data, &got); err != nil {
		t.Fatal(err)
	}
	if got.DeviceID != "hearthlane-ab12cd34" || got.Latitude != -23.55 || got.Longitude != -46.63 {
		t.Fatalf("unexpected body: %+v", got)
	}
	if got.Accuracy == nil || *got.Accuracy != 50 {
		t.Fatalf("missing accuracy: %+v", got.Accuracy)
	}
	if got.Provider == nil || *got.Provider != "network" {
		t.Fatalf("missing provider: %+v", got.Provider)
	}
	if got.RecordedAtEpochMs == nil || *got.RecordedAtEpochMs != 1234567890000 {
		t.Fatalf("missing recordedAtEpochMs: %+v", got.RecordedAtEpochMs)
	}
	if got.PublishedAtEpochMs <= 0 {
		t.Fatalf("publishedAtEpochMs must be generated by the relay, got %d", got.PublishedAtEpochMs)
	}
}

func TestPublishReplacesPrevious(t *testing.T) {
	e := newTestServer(t)
	mustDo(t, e, "PUT", locationURL(e, "d1"), map[string]any{"latitude": 1, "longitude": 2})
	_, d1 := mustDo(t, e, "GET", locationURL(e, "d1"), nil)
	time.Sleep(5 * time.Millisecond)
	mustDo(t, e, "PUT", locationURL(e, "d1"), map[string]any{"latitude": 3, "longitude": 4})
	_, d2 := mustDo(t, e, "GET", locationURL(e, "d1"), nil)

	var loc1, loc2 struct {
		Latitude           float64 `json:"latitude"`
		Longitude          float64 `json:"longitude"`
		PublishedAtEpochMs int64   `json:"publishedAtEpochMs"`
	}
	if err := json.Unmarshal(d1, &loc1); err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(d2, &loc2); err != nil {
		t.Fatal(err)
	}
	if loc2.Latitude != 3 || loc2.Longitude != 4 {
		t.Fatalf("location not replaced: %+v", loc2)
	}
	if loc2.PublishedAtEpochMs < loc1.PublishedAtEpochMs {
		t.Fatalf("publishedAtEpochMs must not decrease: %d -> %d", loc1.PublishedAtEpochMs, loc2.PublishedAtEpochMs)
	}
}

